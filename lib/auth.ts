import { betterAuth } from 'better-auth';
import { nextCookies } from 'better-auth/next-js';
import { PostgresDialect } from 'kysely';
import { pool } from './db';

// No `server-only` import here: the Better Auth CLI (`npx auth generate`) loads this file.

const onVercel = Boolean(process.env.VERCEL);
const configuredHost = process.env.BETTER_AUTH_URL
  ? new URL(process.env.BETTER_AUTH_URL).host
  : undefined;

/**
 * Hosts this deployment answers on. They also become the trusted origins, so
 * preview URLs work without trusting every `*.vercel.app` site.
 */
const allowedHosts = [
  configuredHost,
  process.env.VERCEL_PROJECT_PRODUCTION_URL,
  process.env.VERCEL_BRANCH_URL,
  process.env.VERCEL_URL,
  onVercel ? undefined : 'localhost:*',
].filter((host): host is string => Boolean(host));

const createdAt = 'created_at';
const updatedAt = 'updated_at';

/*
 * Database naming: Better Auth's tables live in the `auth` schema with plural,
 * snake_case names (its defaults are camelCase and singular). `database.casing`
 * isn't implemented by the 1.7 Kysely adapter, so every table and column is
 * mapped explicitly below. When adding a plugin, map its tables and fields too
 * before generating SQL with `npx auth generate`.
 */
export const auth = betterAuth({
  appName: 'Alta Health',
  database: {
    dialect: new PostgresDialect({ pool }),
    type: 'postgres',
    // Qualifies every query with the schema, so it doesn't rely on search_path.
    schemaName: 'auth',
  },
  user: {
    modelName: 'users',
    fields: { emailVerified: 'email_verified', createdAt, updatedAt },
  },
  session: {
    modelName: 'sessions',
    fields: {
      expiresAt: 'expires_at',
      ipAddress: 'ip_address',
      userAgent: 'user_agent',
      userId: 'user_id',
      createdAt,
      updatedAt,
    },
  },
  account: {
    modelName: 'accounts',
    fields: {
      accountId: 'account_id',
      providerId: 'provider_id',
      userId: 'user_id',
      accessToken: 'access_token',
      refreshToken: 'refresh_token',
      idToken: 'id_token',
      accessTokenExpiresAt: 'access_token_expires_at',
      refreshTokenExpiresAt: 'refresh_token_expires_at',
      createdAt,
      updatedAt,
    },
  },
  verification: {
    modelName: 'verifications',
    fields: { expiresAt: 'expires_at', createdAt, updatedAt },
  },
  baseURL: {
    allowedHosts,
    protocol: onVercel ? 'https' : 'http',
    fallback: process.env.BETTER_AUTH_URL,
  },
  emailAndPassword: {
    enabled: true,
  },
  rateLimit: {
    // Serverless instances don't share memory, so counters live in Postgres.
    storage: 'database',
    modelName: 'rate_limits',
    fields: { lastRequest: 'last_request' },
    customRules: {
      '/sign-in/email': { window: 60, max: 5 },
      '/sign-up/email': { window: 60, max: 5 },
    },
  },
  advanced: {
    // uuid primary keys, generated by Postgres (gen_random_uuid()).
    database: { generateId: 'uuid' },
    ipAddress: {
      // Set by Vercel and not overwritable by the client.
      ipAddressHeaders: ['x-vercel-forwarded-for'],
    },
  },
  // Must stay last: applies Set-Cookie headers from auth calls made in Server Actions.
  plugins: [nextCookies()],
});
